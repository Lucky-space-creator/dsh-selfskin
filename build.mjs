/**
 * dsh-selfskin — build script.
 *
 * Zero dependencies on purpose. `npm install` is not a prerequisite for shipping
 * this plugin, and nothing here needs a bundler: the browser artifact is a single
 * `__ModuleLoader__.load({ id, factory })` closure — the exact shape tsdown emits
 * for the shipped `ui-*` packages — so all this script does is assemble that one
 * file and copy the Host half.
 *
 * Assembly order matters and is not cosmetic:
 *   1. injected constants (`SKINS`, `DEFAULT_SKIN_ID`, `CSS`)
 *   2. src/pure.js   — dependency-free helpers (exports stripped)
 *   3. src/derive.js — DIY palette derivation (exports stripped, self-contained)
 *   4. src/client.js — stores, helpers, createPlugin
 *   5. src/ui.js     — React components
 *   6. `return createPlugin(React, h)`
 *
 * pure.js, derive.js, client.js and ui.js are plain scripts that share the
 * factory's scope, so the `const` declarations above them are visible to all of
 * them, and the function declarations in any of them are hoisted for the others.
 * Nothing is evaluated at factory-entry time except the constants, so no
 * temporal-dead-zone read occurs. derive.js is self-contained: it does not reach
 * into pure.js, so its position relative to the others only needs to precede the
 * one call site in ui.js.
 *
 * Usage: node build.mjs
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { BUILTIN_SKINS, DEFAULT_SKIN_ID, HOST_APPEARANCES } from './src/skins.js';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const LIB = join(ROOT, 'lib');

/** Package name; also the module-loader id the browser shell registers. */
const PACKAGE_NAME = 'dsh-selfskin';

/** Read one UTF-8 file. */
async function readText(absolutePath) {
    return readFile(absolutePath, 'utf8');
}

/** Inline every stylesheet, keyed by the effect switch that owns it. */
const CSS = {
    ui: await readText(join(SRC, 'effects', 'ui.css')),
    base: await readText(join(SRC, 'effects', 'buttons.base.css')),
    lift: await readText(join(SRC, 'effects', 'buttons.lift.css')),
    shimmer: await readText(join(SRC, 'effects', 'buttons.shimmer.css')),
    ripple: await readText(join(SRC, 'effects', 'buttons.ripple.css')),
    aurora: await readText(join(SRC, 'effects', 'ambience.aurora.css')),
    wallpaper: await readText(join(SRC, 'effects', 'ambience.wallpaper.css'))
};

/**
 * Strip ES module syntax so a module can be inlined into the factory scope.
 *
 * Only the two forms src/pure.js uses are handled — a line-initial `export ` on a
 * declaration. Anything richer (default exports, re-exports) is out of scope by
 * design: this build has no parser, and a silent mis-strip would ship broken code.
 * @param text - module source.
 * @returns the same source without `export` keywords.
 */
function stripExports(text) {
    if (/^export\s+default/m.test(text) || /^export\s*\{/m.test(text) || /^export\s+\*/m.test(text)) {
        throw new Error('build: unsupported export form in an inlined module; use `export const` / `export function` only');
    }
    return text.replace(/^export\s+/gm, '');
}

/**
 * Indent every line but the first, so an inlined multi-line literal lines up with
 * the declaration it belongs to.
 * @param text - JSON text.
 * @returns indented text.
 */
function indent(text) {
    return text.replace(/\n/g, '\n    ');
}

/**
 * Wrap generated JavaScript in the bundle envelope the shell expects.
 * @param body - factory body.
 * @returns the complete file text.
 */
function wrapBundle(body) {
    return [
        '/* dsh-selfskin - browser bundle.',
        ' * GENERATED by build.mjs from src/. Do not edit this file; edit src/ and rebuild.',
        ' * The shell materializes this file as a closure factory, so `require` is supplied by',
        ' * the browser module table (react is a baseline entry every dynamic bundle may request).',
        ' */',
        'window.__ModuleLoader__.load({',
        '  id: ' + JSON.stringify(PACKAGE_NAME) + ',',
        '  factory(require) {',
        '    const React = require("react");',
        '    const h = React.createElement;',
        '',
        '    /** Built-in skin catalog, inlined from src/skins.js. */',
        '    const SKINS = ' + indent(JSON.stringify(BUILTIN_SKINS, null, 4)) + ';',
        '    /** Sentinel id meaning "follow the host appearance". */',
        '    const DEFAULT_SKIN_ID = ' + JSON.stringify(DEFAULT_SKIN_ID) + ';',
        '    /** The host\'s own appearance preferences, offered alongside the skins. */',
        '    const HOST_APPEARANCES = ' + indent(JSON.stringify(HOST_APPEARANCES, null, 4)) + ';',
        '',
        '    /** CSS inlined from src/effects/*.css; optional blocks are keyed per effect. */',
        '    const CSS = ' + indent(JSON.stringify(CSS, null, 4)) + ';',
        '',
        body,
        '',
        '    return createPlugin(React, h);',
        '  },',
        '});',
        ''
    ].join('\n');
}

await mkdir(LIB, { recursive: true });

// Host half: copied verbatim. It is already valid ESM and needs no transform.
const hostSource = await readText(join(SRC, 'index.js'));
await writeFile(join(LIB, 'index.js'), hostSource, 'utf8');

// Browser half: helpers, then the derivation engine, then the plugin body, then
// the component definitions — all sharing one factory scope.
const pureBody = stripExports(await readText(join(SRC, 'pure.js')));
const deriveBody = stripExports(await readText(join(SRC, 'derive.js')));
const clientBody = await readText(join(SRC, 'client.js'));
const uiBody = await readText(join(SRC, 'ui.js'));
await writeFile(join(LIB, 'client.js'), wrapBundle([pureBody, deriveBody, clientBody, uiBody].join('\n')), 'utf8');

const styleCount = Object.keys(CSS).length;
process.stdout.write(
    'built ' + PACKAGE_NAME + ' -> lib/index.js, lib/client.js'
    + ' (' + styleCount + ' stylesheets, ' + BUILTIN_SKINS.length + ' built-in skins)\n'
);
